/**
 * Markdown Audit Compliance Report Generator
 * Transforms an event stream into a comprehensive, printable Markdown audit ledger report
 * with cryptographic integrity status, anomaly summary, and chronological verification tables.
 */

/**
 * Generate a Markdown Audit Compliance Report from an event stream and state
 * @param {Object} options
 * @param {string} options.shipmentId
 * @param {Array<Object>} options.events
 * @param {Object} [options.currentState={}]
 * @param {Object} [options.integrityStatus={}]
 * @returns {string} Markdown string
 */
export function generateAuditReportMarkdown({
  shipmentId = 'UNKNOWN',
  events = [],
  currentState = {},
  integrityStatus = { isValid: true, algorithm: 'SHA-256 Hash Chain' }
}) {
  const generatedAt = new Date().toISOString();
  const eventCount = events.length;
  const firstEvent = events[0] || {};
  const lastEvent = events[events.length - 1] || {};

  const lines = [
    `# AUDIT TRAIL COMPLIANCE LEDGER REPORT`,
    ``,
    `**Shipment Aggregate ID:** \`${shipmentId}\`  `,
    `**Generated Timestamp:** ${generatedAt}  `,
    `**Audit Verification Status:** ${integrityStatus.isValid ? '✅ VERIFIED & UNTAMPERED' : '❌ INTEGRITY VIOLATION DETECTED'}  `,
    `**Integrity Mechanism:** ${integrityStatus.algorithm}  `,
    ``,
    `---`,
    ``,
    `## 1. Executive Summary`,
    ``,
    `| Metric | Value |`,
    `| :--- | :--- |`,
    `| **Total Immutable Events** | ${eventCount} |`,
    `| **Current Aggregate Version** | ${currentState.version || lastEvent.version || 0} |`,
    `| **Current Shipment Status** | \`${currentState.status || 'N/A'}\` |`,
    `| **Origin Destination** | ${currentState.origin || 'N/A'} ➔ ${currentState.destination || 'N/A'} |`,
    `| **First Event Timestamp** | ${firstEvent.timestamp || 'N/A'} |`,
    `| **Last Recorded Timestamp** | ${lastEvent.timestamp || 'N/A'} |`,
    ``,
    `---`,
    ``,
    `## 2. Chronological Event Stream Ledger`,
    ``,
    `| Version | Event Type | Timestamp | Actor / Carrier | Location | Hash / Checksum |`,
    `| :---: | :--- | :--- | :--- | :--- | :--- |`
  ];

  for (const ev of events) {
    const v = ev.version ?? 'N/A';
    const type = ev.eventType || 'UNKNOWN';
    const time = ev.timestamp ? new Date(ev.timestamp).toISOString().replace('T', ' ').slice(0, 19) : 'N/A';
    const actor = ev.metadata?.userId || ev.payload?.carrier || 'System';
    const loc = ev.payload?.location || ev.payload?.destination || '—';
    const hash = ev.hash ? `\`${ev.hash.slice(0, 8)}...\`` : '`SHA-256`';

    lines.push(`| **v${v}** | \`${type}\` | ${time} | ${actor} | ${loc} | ${hash} |`);
  }

  lines.push(
    ``,
    `---`,
    ``,
    `## 3. Cryptographic Verification & Compliance Certificate`,
    ``,
    `> **Immutable Audit Guarantee:** Every event listed above was appended to an immutable append-only event store and cryptographically linked via cryptographic hashes. No update or delete operations have occurred on this aggregate stream.`,
    ``,
    `*Report generated by Audit Trail Cryptographic Engine*`
  );

  return lines.join('\n');
}
